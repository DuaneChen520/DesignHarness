/**
 * The registry build: turn the real workspace artifacts into the static documents a
 * shadcn client can pull.
 *
 * `@designharness/engine` owns the builders (`buildRegistryItem` / `buildRegistryIndex`),
 * which is where the deterministic key order, the de-duplicated dependency lists and the
 * index projection come from. This module supplies what only the delivery layer knows:
 * where the bytes live, which item depends on which, and the fact that the shadcn schema
 * names the file payload `content` while the engine's internal model calls it `contents`
 * — the single documented rename below.
 *
 * Nothing is written before every document has passed `assertRegistryDocuments`.
 */
import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { join } from 'node:path';
import { buildRegistryIndex, buildRegistryItem } from '@designharness/engine';
import type { RegistryFileInput, RegistryItem } from '@designharness/engine';
import { resolveA11yEvidence } from './a11y.js';
import type { A11yEvidence } from './a11y.js';
import { loadComponentContracts } from './metadata.js';
import type { ComponentContract } from './metadata.js';
import { designMarkdownPath, registryBaseUrl, registryItemsDirName, registryOutputDir, tokensPackageRoot, toRelative } from './paths.js';
import { assertRegistryDocuments } from './schema.js';
import type { RegistryItemDocument } from './schema.js';
import { collectComponentSources, sha256Of, tokenReferences } from './sources.js';
import type { ComponentSource, SourceFile, StyleBundle } from './sources.js';

/** The `registry:base` item every component depends on (TOKEN-API.md §6). */
export const BASE_ITEM_NAME = 'meridian-base';
/** The `registry:style` item that installs the whole styled layer in one go. */
export const STYLE_ITEM_NAME = 'meridian-style';

export interface RegistryBuildOptions {
  /** Directory the documents are written to. Defaults to `packages/registry/registry`. */
  readonly outputDir?: string;
  /** Public URL the registry is served from; baked into `homepage` fields. */
  readonly baseUrl?: string;
  /** Where the component sources live. Overridable so tests can drive a fixture tree. */
  readonly uiSourceRoot?: string;
}

export interface BuiltFile {
  /** Absolute path on disk. */
  readonly path: string;
  /** Path relative to the registry output directory. */
  readonly relativePath: string;
  readonly contents: string;
  readonly bytes: number;
  readonly sha256: string;
}

export interface BuiltRegistry {
  readonly index: ReturnType<typeof buildRegistryIndex>;
  readonly items: readonly RegistryItemDocument[];
  readonly files: readonly BuiltFile[];
  readonly summary: {
    readonly components: readonly string[];
    readonly items: readonly string[];
    readonly distributedBytes: number;
    readonly sourceFilesShipped: number;
  };
}

/** Engine file model (`contents`) → shadcn file model (`content`). */
function toSpecFiles(item: RegistryItem): RegistryItemDocument['files'] {
  return (item.files ?? []).map((file) => {
    const record = file as unknown as { path: string; type: string; contents?: string };
    if (typeof record.contents !== 'string') {
      throw new Error(`registry item "${String(item.name)}" shipped "${record.path}" with no contents`);
    }
    return { path: record.path, type: record.type, content: record.contents };
  });
}

function itemDocument(item: RegistryItem): RegistryItemDocument {
  return { ...(item as unknown as Omit<RegistryItemDocument, 'files'>), files: toSpecFiles(item) };
}

/** Read a required artifact or fail with the command that regenerates it. */
async function requireFile(absolutePath: string, hint: string): Promise<SourceFile> {
  if (!existsSync(absolutePath)) {
    throw new Error(`${toRelative(absolutePath)} does not exist — ${hint}`);
  }
  const content = await readFile(absolutePath, 'utf8');
  if (content.trim().length === 0) throw new Error(`${toRelative(absolutePath)} is empty — ${hint}`);
  return {
    absolutePath,
    sourcePath: toRelative(absolutePath),
    destinationPath: '',
    content,
    sha256: sha256Of(content),
    bytes: Buffer.byteLength(content),
  };
}

/** The entry stylesheet a consuming project imports; every line names a real shipped file. */
function renderEntryStylesheet(options: {
  readonly tokenSheet: string;
  readonly tailwindSheet: string;
  readonly sheets: readonly string[];
}): string {
  const lines = [
    '/*',
    ' * Meridian design system — registry entry stylesheet.',
    ' *',
    ' * Generated by `pnpm --filter @designharness/registry build` (packages/registry/scripts/build.mjs).',
    ' * Do not edit: it is rebuilt from @designharness/tokens\u2019 compiled artifact and the authored',
    ' * component CSS in @designharness/ui, in the cascade order @designharness/ui/styles.css declares.',
    ' *',
    ' * Import this file once from the application entry point, after Tailwind, and every',
    ' * `var(--\u2026)` in the sheets below resolves against the token artifact.',
    ' */',
    '',
    `@import './${options.tokenSheet}';`,
    `@import './${options.tailwindSheet}';`,
    ...options.sheets.map((sheet) => `@import './${sheet}';`),
    '',
  ];
  return lines.join('\n');
}

function indexFile(path: string, relativePath: string, contents: string): BuiltFile {
  return { path, relativePath, contents, bytes: Buffer.byteLength(contents), sha256: sha256Of(contents) };
}

/**
 * Build every document of the registry in memory. Throws when the workspace cannot
 * back an item with real bytes, or when the assembled output violates the schema.
 */
export async function buildRegistry(options: RegistryBuildOptions = {}): Promise<BuiltRegistry> {
  const outputDir = options.outputDir ?? registryOutputDir;
  const baseUrl = (options.baseUrl ?? registryBaseUrl).replace(/\/+$/, '');

  const { components, styles } = await collectComponentSources(options.uiSourceRoot);
  const contracts = await loadComponentContracts(components.map((component) => component.id));

  const tokenSheet = await requireFile(
    join(tokensPackageRoot, 'dist', 'css', 'index.css'),
    'run `pnpm --filter @designharness/tokens build` to compile the token artifact',
  );
  const tailwindSheet = await requireFile(
    join(tokensPackageRoot, 'tailwind', 'theme.css'),
    'run `pnpm --filter @designharness/tokens build` to compile the Tailwind theme',
  );
  const designMd = await requireFile(designMarkdownPath, 'the Intent SSOT is missing from the workspace root');

  /** Shared helpers and system sheets are unioned across components, never invented. */
  const sharedFiles = new Map<string, SourceFile>();
  for (const component of components) {
    for (const file of component.shared) sharedFiles.set(file.destinationPath, file);
  }

  const componentIds = new Set(components.map((component) => component.id));
  const systemSheets = styles.parts.filter((part) => !componentIds.has((part.sourcePath.split('/').pop() ?? '').replace(/\.css$/, '')));
  if (!styles.parts.some((part) => part.sourcePath.endsWith('/motion.css'))) {
    throw new Error(`${styles.barrel.sourcePath} does not import a motion stylesheet; the reduced-motion contract cannot be distributed`);
  }

  const a11yByComponent = new Map<string, A11yEvidence>();
  for (const component of components) {
    a11yByComponent.set(component.id, await resolveA11yEvidence(component.id, component.tokenReferences));
  }

  const items: RegistryItemDocument[] = [];

  // --- registry:component items ------------------------------------------------
  for (const component of components) {
    const contract: ComponentContract | undefined = contracts.get(component.id);
    const a11y = a11yByComponent.get(component.id);
    const files: RegistryFileInput[] = [{ path: component.entry.destinationPath, type: 'registry:component', contents: component.entry.content }];
    if (component.stylesheet !== undefined) {
      files.push({ path: component.stylesheet.destinationPath, type: 'registry:style', contents: component.stylesheet.content });
    }    for (const shared of component.shared) {
      files.push({ path: shared.destinationPath, type: 'registry:lib', contents: shared.content });
    }

    const item = buildRegistryItem(
      {
        name: component.id,
        type: 'registry:component',
        title: component.displayName,
        description: describeComponent(component, styles),
        homepage: `${baseUrl}/r/${component.id}.json`,
        meta: componentMeta(component, contract, a11y, designMd),
      },
      files,
      {
        dependencies: component.npmDependencies,
        registryDependencies: [BASE_ITEM_NAME, ...component.dependsOnComponents],
      },
    );
    items.push(itemDocument(item));
  }

  // --- registry:base ----------------------------------------------------------
  const baseFiles: RegistryFileInput[] = [
    { path: 'styles/designharness/tokens.css', type: 'registry:style', contents: tokenSheet.content },
    { path: 'styles/designharness/tailwind-theme.css', type: 'registry:style', contents: tailwindSheet.content },
  ];
  for (const sheet of systemSheets) {
    baseFiles.push({ path: `styles/designharness/${sheet.sourcePath.split('/').pop() ?? sheet.sourcePath}`, type: 'registry:style', contents: sheet.content });
  }
  for (const [destination, file] of [...sharedFiles.entries()].sort((a, b) => (a[0] < b[0] ? -1 : 1))) {
    baseFiles.push({ path: destination, type: 'registry:lib', contents: file.content });
  }

  items.push(
    itemDocument(
      buildRegistryItem(
        {
          name: BASE_ITEM_NAME,
          type: 'registry:base',
          title: 'Meridian base',
          description:
            'The whole design-system foundation in one item: the compiled DTCG token artifact as CSS custom properties (all four colour modes), the Tailwind v4 @theme, the shared component stylesheet and the class-name helper every Meridian component imports. Every component in this registry declares it as a registry dependency.',
          homepage: `${baseUrl}/r/${BASE_ITEM_NAME}.json`,
          meta: {
            tier: 'base',
            tokens: {
              artifact: tokenSheet.sourcePath,
              sha256: tokenSheet.sha256,
              bytes: tokenSheet.bytes,
              cssCustomProperties: countCustomProperties(tokenSheet.content),
            },
            tailwind: { artifact: tailwindSheet.sourcePath, sha256: tailwindSheet.sha256, bytes: tailwindSheet.bytes },
            shared: {
              stylesheets: systemSheets.map((sheet) => ({ path: sheet.sourcePath, sha256: sheet.sha256 })),
              libraries: [...sharedFiles.values()].map((file) => ({ path: file.sourcePath, sha256: file.sha256 })),
            },
            intent: { file: designMd.sourcePath, sha256: designMd.sha256 },
            modes: ['light', 'dark', 'high-contrast', 'high-contrast-dark'],
          },
        },
        baseFiles,
        {},
      ),
    ),
  );

  // --- registry:style ---------------------------------------------------------
  const entrySheet = renderEntryStylesheet({
    tokenSheet: 'tokens.css',
    tailwindSheet: 'tailwind-theme.css',
    sheets: styles.parts.map((part) => part.sourcePath.split('/').pop() ?? ''),
  });

  items.push(
    itemDocument(
      buildRegistryItem(
        {
          name: STYLE_ITEM_NAME,
          type: 'registry:style',
          title: 'Meridian styled layer',
          description:
            'The aggregate Meridian stylesheet: imports the token artifact, the Tailwind theme, the shared component CSS, every component sheet and the reduced-motion layer, in the cascade order the authored barrel declares. Adding this item installs the base and every component in this registry.',
          homepage: `${baseUrl}/r/${STYLE_ITEM_NAME}.json`,
          meta: {
            tier: 'style',
            entry: 'styles/designharness/index.css',
            barrel: styles.barrel.sourcePath,
            sheets: styles.parts.map((part) => ({ path: part.sourcePath, sha256: part.sha256 })),
            tokenReferences: styles.tokenReferences.length,
          },
        },
        [{ path: 'styles/designharness/index.css', type: 'registry:style', contents: entrySheet }],
        { registryDependencies: [BASE_ITEM_NAME, ...components.map((component) => component.id)] },
      ),
    ),
  );

  // Components sort first so the index reads as a component list, then base, then style.
  const ordered = [...items.filter((item) => item.type === 'registry:component').sort((a, b) => (String(a.name) < String(b.name) ? -1 : 1)), ...items.filter((item) => item.type !== 'registry:component')];

  const index = buildRegistryIndex(
    ordered as unknown as RegistryItem[],
    { name: 'meridian', homepage: `${baseUrl}/registry.json` },
  );

  assertRegistryDocuments(index, ordered);

  const files: BuiltFile[] = [
    indexFile(join(outputDir, 'registry.json'), 'registry.json', serialize(index)),
    indexFile(join(outputDir, 'index.json'), 'index.json', serialize(index)),
    ...ordered.map((item) => indexFile(join(outputDir, registryItemsDirName, `${item.name}.json`), `${registryItemsDirName}/${String(item.name)}.json`, serialize(item))),
  ];

  const sourceFilesShipped = new Set(
    ordered.flatMap((item) => (item.files ?? []).map((file) => `${item.name}:${file.path}:${file.content.length}`)),
  ).size;

  return {
    index,
    items: ordered,
    files,
    summary: {
      components: components.map((component) => component.id),
      items: ordered.map((item) => String(item.name)),
      distributedBytes: files.reduce((total, file) => total + file.bytes, 0),
      sourceFilesShipped,
    },
  };
}

function serialize(value: unknown): string {
  return `${JSON.stringify(value, null, 2)}\n`;
}

function countCustomProperties(css: string): number {
  return new Set([...css.matchAll(/(--[A-Za-z0-9-]+)\s*:/g)].map((match) => match[1])).size;
}

/**
 * The item description is generated from the shipped bytes, not typed by hand: a stale
 * marketing sentence in a registry item is worse than a factual one.
 */
function describeComponent(component: ComponentSource, styles: StyleBundle): string {
  const sheet = component.stylesheet === undefined ? '' : ` Styled by ${component.stylesheet.sourcePath} (${String(component.stylesheet.bytes)} bytes, ${String(component.tokenReferences.length)} token references).`;
  return `Meridian ${component.displayName} — @designharness/ui source distributed verbatim from ${component.entry.sourcePath} (${String(component.entry.bytes)} bytes, sha256 ${component.entry.sha256}). Depends on ${component.npmDependencies.join(', ')}${component.shared.length > 0 ? ` and shares ${component.shared.map((file) => file.sourcePath).join(', ')}` : ''}.${sheet} Registry index barrel: ${styles.barrel.sourcePath}.`;
}

function componentMeta(component: ComponentSource, contract: ComponentContract | undefined, a11y: A11yEvidence | undefined, designMd: SourceFile): Record<string, unknown> {
  return {
    tier: 'component',
    componentId: component.id,
    displayName: component.displayName,
    entry: { path: component.entry.sourcePath, sha256: component.entry.sha256, bytes: component.entry.bytes },
    stylesheet:
      component.stylesheet === undefined
        ? null
        : { path: component.stylesheet.sourcePath, sha256: component.stylesheet.sha256, bytes: component.stylesheet.bytes },
    shared: component.shared.map((file) => ({ path: file.sourcePath, sha256: file.sha256, bytes: file.bytes })),
    npmDependencies: component.npmDependencies,
    interComponentDependencies: component.dependsOnComponents,
    stories: component.hasStories ? { path: component.storiesPath ?? '' } : null,
    tokenReferences: component.tokenReferences,
    tokensReferenced: component.tokenReferences.length,
    props: contract?.props ?? [],
    propCount: contract?.props.length ?? 0,
    contractPropCount: contract?.totalProps ?? 0,
    requiredPropCount: contract === undefined ? 0 : contract.props.filter((prop) => prop.required).length,
    documentedPropCount: contract === undefined ? 0 : contract.props.filter((prop) => prop.description !== undefined).length,
    events: contract?.events ?? [],
    metadataProvenance: contract?.provenance ?? 'unavailable',
    metadataSource: contract?.source ?? 'none',
    a11y: a11y ?? null,
    intent: { file: designMd.sourcePath, sha256: designMd.sha256 },
  };
}

/** Write a built registry to disk, replacing any previous `r/` output. */
export async function writeRegistry(built: BuiltRegistry, outputDir: string = registryOutputDir): Promise<readonly BuiltFile[]> {
  await rm(join(outputDir, registryItemsDirName), { recursive: true, force: true });
  await mkdir(join(outputDir, registryItemsDirName), { recursive: true });
  for (const file of built.files) {
    await mkdir(join(file.path, '..'), { recursive: true });
    await writeFile(file.path, file.contents, 'utf8');
  }
  return built.files;
}

/** Build, validate and write in one call — what `scripts/build.mjs` and the CLI run. */
export async function buildAndWriteRegistry(options: RegistryBuildOptions = {}): Promise<BuiltRegistry> {
  const built = await buildRegistry(options);
  await writeRegistry(built, options.outputDir ?? registryOutputDir);
  return built;
}

/** Read a previously built document; `undefined` when the registry has not been built. */
export async function readRegistryDocument(absolutePath: string): Promise<unknown | undefined> {
  if (!existsSync(absolutePath)) return undefined;
  return JSON.parse(await readFile(absolutePath, 'utf8')) as unknown;
}

