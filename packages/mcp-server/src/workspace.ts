/**
 * Workspace paths for the MCP server.
 *
 * The server is a long-lived process started by an AI client from an arbitrary working
 * directory, so every input is resolved from this module's location and the result is
 * reported verbatim in tool output. There are no embedded lists of components or tokens:
 * if the artifact on disk changes, the answers change with it.
 */
import { existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

function findWorkspaceRoot(start: string): string {
  let current = resolve(start);
  for (;;) {
    if (existsSync(join(current, 'pnpm-workspace.yaml'))) return current;
    const parent = dirname(current);
    if (parent === current) throw new Error(`no pnpm-workspace.yaml above ${start}`);
    current = parent;
  }
}

/** `packages/mcp-server/{src,dist}` -> `packages` -> repository root. */
export const workspaceRoot: string = process.env['DESIGNHARNESS_WORKSPACE_ROOT'] ?? findWorkspaceRoot(resolve(dirname(fileURLToPath(import.meta.url)), '..', '..'));

export const tokensPackageRoot: string = join(workspaceRoot, 'packages', 'tokens');
/** DTCG 2025.10 artifact — the value/tier/provenance source of truth. */
export const dtcgArtifactPath: string = join(tokensPackageRoot, 'tokens.json');
/** Compiled recipe module: resolved values per mode, generated by the tokens build. */
export const tokenRecipePath: string = join(tokensPackageRoot, 'dist', 'recipe', 'index.js');
/** Flat resolved JSON, generated by Style Dictionary. */
export const flatTokensPath: string = join(tokensPackageRoot, 'dist', 'json', 'tokens.json');
export const cssArtifactPath: string = join(tokensPackageRoot, 'dist', 'css', 'index.css');

export const uiSourceRoot: string = join(workspaceRoot, 'packages', 'ui', 'src');
export const contractsMetadataPath: string = join(workspaceRoot, 'packages', 'contracts', 'generated', 'component-metadata.json');
export const builtRegistryDir: string = join(workspaceRoot, 'packages', 'registry', 'registry');
export const designMarkdownPath: string = join(workspaceRoot, 'DESIGN.md');

/** Repository-relative POSIX path, for the provenance fields in tool output. */
export function toRelative(absolutePath: string): string {
  const root = workspaceRoot.replace(/\\/g, '/');
  const posix = absolutePath.replace(/\\/g, '/');
  return posix.startsWith(`${root}/`) ? posix.slice(root.length + 1) : posix;
}
