/**
 * Custom Style Dictionary formats implementing the TOKEN-API output contract:
 *  - per-mode CSS custom properties + the `:root` / `[data-theme]` /
 *    `prefers-color-scheme` cascade (`harness/css`);
 *  - Tailwind v4 `@theme` (`harness/tailwind`);
 *  - flat resolved JSON (`harness/json-flat`);
 *  - the JS recipe + TS declaration (`harness/recipe`, `harness/recipe-types`).
 *
 * Every emitter reads the full transformed dictionary and picks its own subset, so
 * output is deterministic regardless of platform/file ordering. `harnessMode` is
 * passed via the (extensible) platform config.
 */
import type { ResolvedSets } from './sets.js';
import { colorSchemeFor, MODES, type Mode } from './values.js';
import { hexToRgb, oklchStringToHex } from '../colors/convert.js';

const HEADER =
  '/*\n * GENERATED by @designharness/engine — DO NOT EDIT.\n * Pipeline: DESIGN.md (Intent SSOT) → DTCG artifact → Style Dictionary v5.\n */';

/** Escape a value for embedding in a generated TS/JS string literal. */
function jsString(value: string): string {
  return JSON.stringify(value);
}

/**
 * The banner as *line* comments. `HEADER` is a CSS block comment, so it cannot be
 * pasted into JS by swapping the delimiters — the inner ` * …` lines would parse as
 * code and make the emitted module a syntax error.
 */
function jsHeader(): string {
  return HEADER.split('\n')
    .map((line) => line.replace(/^\s*\/?\*+\/?\s?/, '').trimEnd())
    .filter((line) => line.length > 0)
    .map((line) => `// ${line}`.trimEnd())
    .join('\n');
}

function varLines(entries: Iterable<readonly [string, string]>, indent = '  '): string[] {
  const out: string[] = [];
  for (const [name, value] of entries) out.push(`${indent}--${name}: ${value};`);
  return out;
}

/** Full cascade index.css (TOKEN-API §3). */
export function renderCssIndex(sets: ResolvedSets): string {
  const lines: string[] = [HEADER, ''];
  lines.push(':root, [data-theme="light"] {');
  lines.push(`  color-scheme: ${colorSchemeFor('light')};`);
  lines.push(...varLines(Object.entries(sets.base)));
  lines.push(...varLines(Object.entries(sets.primitives)));
  lines.push(...varLines(Object.entries(sets.semantics.light)));
  lines.push('}');
  lines.push('');
  for (const mode of ['dark', 'high-contrast', 'high-contrast-dark'] as const) {
    const selector = `[data-theme="${mode}"]`;
    lines.push(`${selector} {`);
    lines.push(`  color-scheme: ${colorSchemeFor(mode)};`);
    lines.push(...varLines(Object.entries(sets.semantics[mode])));
    lines.push('}');
    lines.push('');
  }
  // prefers-color-scheme fallback mirrors the dark semantic block.
  lines.push('@media (prefers-color-scheme: dark) {');
  lines.push('  :root:not([data-theme="light"]) {');
  lines.push(`    color-scheme: ${colorSchemeFor('dark')};`);
  lines.push(...varLines(Object.entries(sets.semantics.dark), '    '));
  lines.push('  }');
  lines.push('}');
  lines.push('');
  return lines.join('\n');
}

/** A single-mode CSS file (self-contained: base + primitives + that mode's semantics). */
export function renderCssMode(sets: ResolvedSets, mode: Mode): string {
  const lines: string[] = [HEADER, ''];
  lines.push(':root {');
  lines.push(`  color-scheme: ${colorSchemeFor(mode)};`);
  lines.push(...varLines(Object.entries(sets.base)));
  if (mode === 'light') lines.push(...varLines(Object.entries(sets.primitives)));
  lines.push(...varLines(Object.entries(sets.semantics[mode])));
  lines.push('}');
  lines.push('');
  return lines.join('\n');
}

/** Tailwind v4 `@theme` block mapping public tokens to Tailwind namespaces. */
export function renderTailwindTheme(sets: ResolvedSets): string {
  const lines: string[] = [HEADER, '', '@theme {'];
  const push = (line: string): void => {
    lines.push(`  ${line}`);
  };

  for (const [name, value] of Object.entries(sets.semantics.light)) push(`--${name}: ${value};`);

  for (const [name, value] of Object.entries(sets.base)) {
    if (name.startsWith('space-')) push(`--spacing-${name.slice('space-'.length)}: ${value};`);
    else if (name.startsWith('radius-')) push(`--${name}: ${value};`);
    else if (name.startsWith('border-width-')) push(`--${name}: ${value};`);
    else if (name.startsWith('font-family-')) push(`--font-${name.slice('font-family-'.length)}: ${value};`);
    else if (name.startsWith('font-size-')) {
      const leaf = name.slice('font-size-'.length);
      push(`--text-${leaf}: ${value};`);
      const lh = sets.base[`line-height-${leaf}`];
      if (lh !== undefined) push(`--text-${leaf}--line-height: ${lh};`);
      const ls = sets.base[`letter-spacing-${leaf}`];
      if (ls !== undefined) push(`--text-${leaf}--letter-spacing: ${ls};`);
    } else if (name.startsWith('font-weight-')) push(`--${name}: ${value};`);
    else if (name.startsWith('line-height-')) {
      const leaf = name.slice('line-height-'.length);
      if (sets.base[`font-size-${leaf}`] === undefined) push(`--leading-${leaf}: ${value};`);
    } else if (name.startsWith('elevation-')) push(`--shadow-${name}: ${value};`);
    else if (name.startsWith('easing-')) push(`--ease-${name.slice('easing-'.length)}: ${value};`);
    else if (name.startsWith('control-height-')) push(`--size-${name.slice('control-'.length)}: ${value};`);
  }

  const fast = sets.base['duration-fast'];
  if (fast !== undefined) push(`--default-transition-duration: ${fast};`);
  lines.push('}');
  lines.push('');
  return lines.join('\n');
}

/** Flat resolved JSON for the light/base surface, keys sorted for determinism. */
export function renderFlatJson(sets: ResolvedSets): string {
  const flat: Record<string, string> = { ...sets.primitives, ...sets.base, ...sets.semantics.light };
  const sorted: Record<string, string> = {};
  for (const key of Object.keys(flat).sort()) sorted[key] = flat[key] as string;
  return `${JSON.stringify(sorted, null, 2)}\n`;
}

function perModeMaps(sets: ResolvedSets): Record<Mode, Record<string, string>> {
  const out = {} as Record<Mode, Record<string, string>>;
  for (const mode of MODES) out[mode] = { ...sets.base, ...sets.semantics[mode] };
  return out;
}

/** JS recipe module: `tokens` (light flat), `modes`, `semanticRoles`. */
export function renderRecipe(sets: ResolvedSets): string {
  const light = { ...sets.primitives, ...sets.base, ...sets.semantics.light };
  const lines: string[] = [
    jsHeader(),
    '',
    '/** Light/base resolved token values, keyed by public CSS name (no `--`). */',
    'export const tokens = ' + JSON.stringify(sortObj(light), null, 2) + ';',
    '',
    '/** Resolved token values per colour mode. */',
    'export const modes = ' + JSON.stringify(mapObj(perModeMaps(sets) as unknown as Record<string, Record<string, string>>, sortObj), null, 2) + ';',
    '',
    '/** Public semantic colour role names (light tier). */',
    'export const semanticRoles = ' + JSON.stringify([...sets.semanticRoleNames].sort()) + ';',
    '',
  ];
  return lines.join('\n');
}

/** TS declaration companion to the recipe. */
export function renderRecipeTypes(sets: ResolvedSets): string {
  const light = { ...sets.primitives, ...sets.base, ...sets.semantics.light };
  const names = Object.keys(light).sort();
  const roleNames = [...sets.semanticRoleNames].sort();
  const nameUnion = names.length > 0 ? names.map((n) => jsString(n)).join(' | ') : 'never';
  const roleUnion = roleNames.length > 0 ? roleNames.map((n) => jsString(n)).join(' | ') : 'string';
  const lines: string[] = [
    'export type Mode = "light" | "dark" | "high-contrast" | "high-contrast-dark";',
    `export type TokenName = ${nameUnion};`,
    '',
    'export declare const tokens: Record<TokenName, string>;',
    'export declare const modes: Record<Mode, Record<string, string>>;',
    `export declare const semanticRoles: readonly (${roleUnion})[];`,
    '',
  ];
  return lines.join('\n');
}

function sortObj(obj: Record<string, string>): Record<string, string> {
  const out: Record<string, string> = {};
  for (const key of Object.keys(obj).sort()) out[key] = obj[key] as string;
  return out;
}

function mapObj(obj: Record<string, Record<string, string>>, fn: (v: Record<string, string>) => Record<string, string>): Record<string, Record<string, string>> {
  const out: Record<string, Record<string, string>> = {};
  for (const key of Object.keys(obj).sort()) {
    out[key] = fn(obj[key] as Record<string, string>);
  }
  return out;
}

function stripColorPrefix(name: string): string {
  if (name.startsWith('color-primitive-')) return `primitive-${name.slice('color-primitive-'.length)}`;
  if (name.startsWith('color-')) return name.slice('color-'.length);
  return name;
}

function toPascalCase(name: string): string {
  const clean = stripColorPrefix(name);
  return clean
    .split('-')
    .filter((part) => part.length > 0)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join('');
}

function toCamelCase(name: string): string {
  const pascal = toPascalCase(name);
  if (pascal.length === 0) return '';
  return pascal.charAt(0).toLowerCase() + pascal.slice(1);
}

/** Formats tokens into flat $color-* variables and a structured $tokens map. */
export function renderScssTokens(sets: ResolvedSets): string {
  const lines: string[] = [HEADER, ''];
  const allTokens: Record<string, string> = {
    ...sets.primitives,
    ...sets.base,
    ...sets.semantics.light,
  };
  const sortedNames = Object.keys(allTokens).sort();

  // 1. Flat variables
  for (const name of sortedNames) {
    const val = allTokens[name]!;
    lines.push(`$${name}: ${val};`);
  }
  lines.push('');

  // 2. Structured $tokens map
  lines.push('$tokens: (');
  for (const name of sortedNames) {
    lines.push(`  "${name}": $${name},`);
  }
  lines.push(');');
  lines.push('');
  return lines.join('\n');
}

/** Formats color tokens into Kotlin singleton object `Color` under package `com.designharness.tokens`. */
export function renderComposeColor(sets: ResolvedSets): string {
  const lines: string[] = [
    '// GENERATED by @designharness/engine — DO NOT EDIT.',
    '// Pipeline: DESIGN.md (Intent SSOT) → DTCG artifact → Style Dictionary v5.',
    '',
    'package com.designharness.tokens',
    '',
    'import androidx.compose.ui.graphics.Color',
    '',
    'object Color {',
  ];

  const colorTokens: Record<string, string> = {
    ...sets.primitives,
    ...sets.semantics.light,
  };
  for (const [name, val] of Object.entries(sets.base)) {
    if (name.startsWith('color-')) colorTokens[name] = val;
  }

  const sortedNames = Object.keys(colorTokens).sort();
  for (const name of sortedNames) {
    const val = colorTokens[name]!;
    const hex = oklchStringToHex(val);
    const composeHex = `0xFF${hex.replace('#', '').toUpperCase()}`;
    const propName = toPascalCase(name);
    lines.push(`    val ${propName} = Color(${composeHex})`);
  }

  lines.push('}');
  lines.push('');
  return lines.join('\n');
}

/** Formats color tokens into `SwiftUI.Color` extension with public static properties. */
export function renderSwiftColorAsset(sets: ResolvedSets): string {
  const lines: string[] = [
    '// GENERATED by @designharness/engine — DO NOT EDIT.',
    '// Pipeline: DESIGN.md (Intent SSOT) → DTCG artifact → Style Dictionary v5.',
    '',
    'import SwiftUI',
    '',
    'public extension Color {',
  ];

  const colorTokens: Record<string, string> = {
    ...sets.primitives,
    ...sets.semantics.light,
  };
  for (const [name, val] of Object.entries(sets.base)) {
    if (name.startsWith('color-')) colorTokens[name] = val;
  }

  const sortedNames = Object.keys(colorTokens).sort();
  for (const name of sortedNames) {
    const val = colorTokens[name]!;
    const hex = oklchStringToHex(val);
    const [r, g, b] = hexToRgb(hex);
    const red = (r / 255).toFixed(4);
    const green = (g / 255).toFixed(4);
    const blue = (b / 255).toFixed(4);
    const propName = toCamelCase(name);
    lines.push(`    static let ${propName} = Color(red: ${red}, green: ${green}, blue: ${blue})`);
  }

  lines.push('}');
  lines.push('');
  return lines.join('\n');
}
